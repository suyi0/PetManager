def paragraph_text(p):
    parts = []
    for node in p.iter():
        if node.tag == f"{{{W}}}t":
            parts.append(node.text or "")
        elif node.tag == f"{{{W}}}tab":
            parts.append("\t")
        elif node.tag == f"{{{W}}}br":
            parts.append("\n")
    return "".join(parts)


def set_paragraph_text(p, text):
    text_nodes = [node for node in p.iter() if node.tag == f"{{{W}}}t"]
    if not text_nodes:
        return False
    text_nodes[0].text = text
    text_nodes[0].set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    for node in text_nodes[1:]:
        node.text = ""
    return True


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: rewrite_docx_paragraphs.py <input.docx> <output.docx>")
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    shutil.copyfile(src, dst)

    with zipfile.ZipFile(src, "r") as zin:
        document_xml = zin.read("word/document.xml")
        entries = {info.filename: zin.read(info.filename) for info in zin.infolist()}
        infos = zin.infolist()

    root = ET.fromstring(document_xml)
    paragraphs = root.findall(".//w:p", NS)
    changed = []
    missing = []
    for idx, new_text in REPLACEMENTS.items():
        if idx >= len(paragraphs):
            missing.append(idx)
            continue
        old = paragraph_text(paragraphs[idx]).strip()
        if not old:
            missing.append(idx)
            continue
        set_paragraph_text(paragraphs[idx], new_text)
        changed.append((idx, old, new_text))

    entries["word/document.xml"] = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    with zipfile.ZipFile(dst, "w") as zout:
        for info in infos:
            zout.writestr(info, entries[info.filename])

    print(f"changed={len(changed)}")
    if missing:
        print("missing=" + ",".join(map(str, missing)))
    for idx, old, new in changed:
        print(f"{idx}\t{len(old)}->{len(new)}")


if __name__ == "__main__":
    main()
